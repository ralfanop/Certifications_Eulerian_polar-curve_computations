#!/usr/bin/env python3
"""Strict fixed 30,000-decimal-place replay of a successful prior Arb certificate.

Input is the GitHub Actions artifact generated by million_decimal_common.py.
Its 1,000,001-digit significand M and decimal exponent e are NOT treated as
an arbitrary approximation: the upstream SUCCESS CI strictly proved the
true Arb enclosure lies inside the open rational rounding interval

    (2*M - 1) / (2*10**(1_000_000-e))
      < x <
    (2*M + 1) / (2*10**(1_000_000-e)).

This replay uses FLINT exact integers to prove that the *whole previous
rigorously certified interval*, not just M, fits strictly inside ONE
nearest-10**(-30000) rounding cell. It does not need to rerun expensive
3.6-million-bit transcendental evaluation, nor to assume that an arbitrary
million-digit string is exact. Prior successful workflow and unchanged
artifact content are explicit prerequisite evidence, provided by CI.

The 30k output is a deduction from a certified Arb enclosure, not a new
direct 3.6M-bit Arb evaluation. No proof of underlying integral identities
or symbolic expressions is claimed.
"""
import argparse
import gzip
import hashlib
import json
import re
from functools import lru_cache
from pathlib import Path

import flint
from flint import fmpz

DIGITS = 1000001
PLACES = 30000
MINIMUM_BITS = 3400000
assert flint.__version__ == "0.9.0"
Q = fmpz(10) ** PLACES


@lru_cache(maxsize=128)
def denominator_for_exp(exp):
    k = DIGITS - 1 - exp
    assert k >= 0, ("Exponent too large for this fixed-place replay", exp)
    assert k < 2000000, ("Unexpected numeric magnitude", exp)
    return fmpz(10) ** k


def fixed_decimal_from_significant(value):
    assert isinstance(value, str)
    mantissa, exponent = value.rsplit("e", 1)
    assert re.fullmatch(r"[+-]?\\d+", exponent), "Invalid decimal exponent"
    exponent = int(exponent)
    is_negative = mantissa.startswith("-")
    if is_negative:
        mantissa = mantissa[1:]
    left, right = mantissa.split(".", 1)
    assert len(left) == 1 and left in "123456789"
    assert len(right) == DIGITS - 1 and right.isascii() and right.isdigit()
    m = fmpz(left + right)
    if is_negative:
        m = -m
    d = denominator_for_exp(exponent)
    assert d > 0
    # The genuine x is rigorously inside ((2m-1)/(2d),(2m+1)/(2d)).
    # Select the only candidate n for rounding at exactly 30000 places.
    n = (2 * m * Q + d) // (2 * d)
    # Strictly verify BOTH exact rational sides of the old rounding cell
    # inside the new cell ((2n-1)/(2Q),(2n+1)/(2Q)).
    assert (2 * m - 1) * Q > (2 * n - 1) * d, (
        "Lower half-ulp boundary ambiguity", exponent)
    assert (2 * m + 1) * Q < (2 * n + 1) * d, (
        "Upper half-ulp boundary ambiguity", exponent)

    sign = "-" if n < 0 else ""
    a = abs(n)
    decimal = sign + str(a // Q) + "." + str(a % Q).zfill(PLACES)
    assert len(decimal.split(".")[1]) == PLACES
    return decimal, exponent


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--label", required=True,
                   help="Unique label for the exact upstream GitHub Actions artifact")
    p.add_argument("--source-run", required=True, type=int)
    p.add_argument("--source-artifact", required=True)
    args = p.parse_args()
    assert re.fullmatch(r"[a-z0-9_-]+", args.label)
    assert re.fullmatch(r"[a-zA-Z0-9_-]+", args.source_artifact)

    source = Path("million-enclosures.jsonl.gz")
    assert source.is_file() and source.stat().st_size > 0
    meta_paths = list(Path().glob("million-*.json"))
    assert len(meta_paths) == 1, ("One original summary is mandatory", meta_paths)
    metadata = json.loads(meta_paths[0].read_text())
    assert metadata["python_flint"] == "0.9.0"
    assert metadata["working_bits"] == 3600000
    assert metadata["required_relative_bits"] == MINIMUM_BITS
    assert metadata["significant_digits"] == DIGITS
    assert metadata["minimum_relative_bits"] >= MINIMUM_BITS

    source_digest = hashlib.file_digest(source.open("rb"), "sha256").hexdigest()
    outpath = Path("arb30000-" + args.label + ".jsonl.gz")
    n = 0
    records = []
    with gzip.open(source, "rt", encoding="utf-8") as inp, gzip.open(
        outpath, "wt", encoding="utf-8", compresslevel=1
    ) as out:
        for line in inp:
            old = json.loads(line)
            assert old.get("arb_ball"), "Require archived outward-rounded Arb ball"
            bits = int(old["relative_bits"])
            assert bits >= MINIMUM_BITS
            fixed, exponent = fixed_decimal_from_significant(
                old["rounded_significant_digits"])
            sha = hashlib.sha256(fixed.encode("ascii")).hexdigest()
            result = {"name":old["name"],
                      "decimal_places_after_point":PLACES,
                      "rounded_decimal":fixed,
                      "rounded_sha256":sha,
                      "original_relative_bits":bits,
                      "original_decimal_exponent":exponent,
                      "strict_full_interval_contained_in_fixed_30000_cell":True}
            out.write(json.dumps(result,ensure_ascii=True)+"\n")
            records.append({"name":old["name"],"rounded_sha256":sha})
            n += 1
    assert n and n == len(metadata["certificates"]), (
        "Incomplete source artifact / certificate count",n,len(metadata["certificates"]))
    assert [x["name"] for x in records] == [
        x["name"] for x in metadata["certificates"]]
    summary = {"status":"CERTIFIED_BY_EXACT_REPLAY",
               "method":"FLINT exact fmpz inequality from a previously strict Arb 1000001-significant-digit ball",
               "decimal_places_after_point":PLACES,
               "upstream_arb_working_bits":3600000,
               "upstream_min_verified_relative_bits":metadata["minimum_relative_bits"],
               "source_ci_run_id":args.source_run,
               "source_artifact_name":args.source_artifact,
               "source_gzip_sha256":source_digest,
               "certificate_count":n,
               "certificates":records,
               "logical_scope":"Rounding of previously rigorously enclosed expressions; does not imply their analytic derivations"}
    Path("arb30000-"+args.label+".json").write_text(
        json.dumps(summary,indent=2),encoding="utf-8")
    print("SUCCESS STRICT 30000 FIXED DECIMAL ARB REPLAY",
          args.label, "records", n,
          "original minimum relative bits",metadata["minimum_relative_bits"],
          "source SHA256",source_digest,flush=True)


if __name__ == "__main__":
    main()
